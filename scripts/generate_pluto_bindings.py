"""Generate auditable relocation tables for the pinned public Pluto DLLs.

Usage:
  generate_pluto_bindings.py OUT.h RELEASE:SHA256:PATH_TO_PLUTO_DLL [RELEASE:SHA256:PATH ...]

One table is written per release; LegacyView::bind() picks the table whose every entry matches the loaded
DLL, so several Pluto releases can be supported side by side. The first release is also exposed as
`pluto_bindings` (the optional observation probe is pinned to it).
Dependencies: pefile, capstone. The input DLLs are never modified.
"""
import argparse, hashlib, pathlib, re, struct
import capstone, pefile

# Absolute addresses in StarCraft 1.16.1 that the bridge emulates (see LegacyView).
SINGLE = {0x485a40, 0x512688, 0x59688c, 0x596904, 0x6283ec, 0x6283f4, 0x628430, 0x64dec4, 0x654880, 0x654aa0, 0x6d1260}
def known(v):
    return v in SINGLE or 0x5124d8 <= v < 0x512510 or 0x57eee0 <= v < 0x5967f0 or 0x59cca8 <= v < 0x59cdf8

def rows_for(dll, expected_hash):
    raw = dll.read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected_hash:
        raise SystemExit(f'{dll}: SHA-256 mismatch (expected {expected_hash})')
    pe = pefile.PE(data=raw); base = pe.OPTIONAL_HEADER.ImageBase
    cs = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32); cs.detail = True; cs.skipdata = True
    rows = []
    for sec in pe.sections:
        if not sec.Characteristics & 0x20000000: continue
        for ins in cs.disasm(sec.get_data(), base + sec.VirtualAddress):
            if not ins.id: continue
            for op in ins.operands:
                if op.type == capstone.x86.X86_OP_MEM: val, off, size = op.mem.disp, ins.disp_offset, ins.disp_size
                elif op.type == capstone.x86.X86_OP_IMM and ins.mnemonic not in ('call', 'jmp'): val, off, size = op.imm, ins.imm_offset, ins.imm_size
                else: continue
                signed = (val + 0x80000000) % 0x100000000 - 0x80000000
                if not known(abs(signed)): continue
                assert size == 4
                word = val & 0xffffffff
                assert struct.unpack_from('<I', ins.bytes, off)[0] == word
                rows.append(f'  {{0x{ins.address - base + off:x},0x{word:08x}}}, // {ins.address - base:x}: {ins.mnemonic} {ins.op_str}')
    return rows

p = argparse.ArgumentParser()
p.add_argument('out', type=pathlib.Path)
p.add_argument('releases', nargs='+', help='RELEASE:SHA256:PATH')
args = p.parse_args()
parts = []; sets = []; first = None
for spec in args.releases:
    release, expected, path = spec.split(':', 2)
    ident = 'pluto_bindings_' + re.sub(r'\W', '_', release)
    first = first or ident
    rows = rows_for(pathlib.Path(path), expected)
    print(f'{release}: {len(rows)} verified address operands')
    parts.append(f'// {release} (pluto.dll sha256 {expected})\ninline constexpr PlutoBinding {ident}[]={{\n' + '\n'.join(rows) + '\n};\n')
    sets.append(f'  {{"{release}",{ident},sizeof({ident})/sizeof(PlutoBinding)}},')
args.out.write_text(
    '#pragma once\n#include <cstddef>\n#include <cstdint>\n'
    '// Generated by scripts/generate_pluto_bindings.py. Do not edit; regenerate for each supported Pluto release.\n'
    'struct PlutoBinding {uint32_t rva;uint32_t expected;};\n'
    'struct PlutoBindingSet {const char* release;const PlutoBinding* bindings;size_t count;};\n'
    + '\n'.join(parts) +
    f'inline constexpr const auto& pluto_bindings={first};  // the first release; used by the observation probe\n'
    'inline constexpr PlutoBindingSet pluto_binding_sets[]={\n' + '\n'.join(sets) + '\n};\n')
